"""Generate telemetria_server/udp/structs.py (numpy dtypes) from the packed C headers in docs/udp-spec.

Headers are read as text only. Usage: python tools/gen_udp_structs.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SPEC = ROOT / "docs/udp-spec/f1-25-2026-format"
OUT = ROOT / "telemetria_server/udp/structs.py"

PRIM = {"uint8_t": "u1", "int8_t": "i1", "char": "S1", "uint16_t": "<u2", "int16_t": "<i2",
        "uint32_t": "<u4", "int32_t": "<i4", "float": "<f4", "uint64_t": "<u8", "int64_t": "<i8", "double": "<f8"}

src = "\n".join(p.read_text(encoding="utf-8", errors="replace") for p in sorted(SPEC.glob("*.h")))
src = re.sub(r"//[^\n]*", "", src)
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)


def match(text, start):
    depth = 0
    for i in range(start, len(text)):
        depth += (text[i] == "{") - (text[i] == "}")
        if depth == 0:
            return i
    raise ValueError


def fields(body):
    """[(name, type, dims)] of simple member declarations."""
    return [(n, t, tuple(int(d) for d in re.findall(r"\d+", dims)))
            for t, n, dims in re.findall(r"^\s*(\w+)\s+(\w+)((?:\s*\[\s*\d+\s*\])*)\s*;", body, flags=re.M)
            if t not in ("return", "using", "virtual")]


structs = {}   # plain structs: name -> fields
packets = {}   # packet classes: name -> fields (private members, trailing '_' stripped)
unions = {}    # union members: member name -> fields
for m in re.finditer(r"\b(struct|class|union)\s+(\w+)\s*(?::\s*public\s+\w+\s*)?\{", src):
    kind, name = m.group(1), m.group(2)
    body = src[m.end():match(src, m.end() - 1)]
    if kind == "struct":
        structs[name] = fields(body)
    elif kind == "class" and name != "PHeader":
        priv = re.search(r"private:(.*)", body, flags=re.S)
        packets[name] = [(n.rstrip("_"), t, d) for n, t, d in fields(priv.group(1))] if priv else []
    elif kind == "union":
        for sm in re.finditer(r"struct\s*\{", body):
            sb = body[sm.end():match(body, sm.end() - 1)]
            tail = re.match(r"\s*(\w+)\s*;", body[match(body, sm.end() - 1) + 1:])
            unions[tail.group(1)] = fields(sb)


def dt(fs):
    out = []
    for n, t, dims in fs:
        base = PRIM.get(t, f"{t}_DT")
        out.append(f"        ({n!r}, {base!r}{', ' + repr(dims) if dims else ''}),"
                   if t in PRIM else f"        ({n!r}, {t}_DT{', ' + repr(dims) if dims else ''}),")
    return "\n".join(out)


lines = ['"""numpy dtypes for the F1 25 "2026 format" UDP packets. GENERATED by tools/gen_udp_structs.py - do not edit.',
         '',
         'Source: docs/udp-spec/f1-25-2026-format (packed C layouts, little-endian). Each ``*_DT`` is the payload',
         'after the 29-byte header; ``PACKET_DT[packet_id]`` is the full packet including the header.',
         '"""',
         '',
         'import numpy as np',
         '',
         'HEADER_DT = np.dtype([',
         ]
hdr = structs["PacketHeader"]
lines.append(dt(hdr))
lines += ["])", ""]

order = []
def emit(name, fs, suffix="_DT"):
    lines.append(f"{name}{suffix} = np.dtype([")
    lines.append(dt(fs))
    lines.extend(["])", ""])

# dependency order for plain structs
done = {"PacketHeader"}
pending = {k: v for k, v in structs.items() if k != "PacketHeader"}
while pending:
    progressed = False
    for k, v in list(pending.items()):
        if all(t in PRIM or t in done for _n, t, _d in v):
            emit(k, v); done.add(k); del pending[k]; progressed = True
    if not progressed:
        raise SystemExit(f"unresolved: {list(pending)}")

for k, v in unions.items():
    emit("EventDetails_" + k, v)

lines.append("EventDataDetails_DT = np.dtype(f\"V{max(d.itemsize for n, d in list(globals().items()) if n.startswith('EventDetails_'))}\")")
lines.append("")
packet_names = {}
for k, v in packets.items():
    emit(k, v, "_PAYLOAD_DT")

IDS = {"PacketMotionData": 0, "PacketSessionData": 1, "PacketLapData": 2, "PacketEventData": 3,
       "PacketParticipantData": 4, "PacketCarSetupData": 5, "PacketCarTelemetryData": 6,
       "PacketCarStatusData": 7, "PacketFinalClassificationData": 8, "PacketLobbyInfo": 9,
       "PacketCarDamageData": 10, "PacketSessionHistoryData": 11, "PacketTyreSetData": 12,
       "PacketMotionEXData": 13, "PacketTimeTrialData": 14, "PacketLapPositionsData": 15,
       "PacketCarTelemetryData2": 16}
lines.append("PACKET_DT = {  # packet id -> full packet (header + payload)")
for k, i in IDS.items():
    lines.append(f"    {i}: np.dtype([('header', HEADER_DT), ('body', {k}_PAYLOAD_DT)]),")
lines += ["}", ""]
pathlib.Path(OUT).write_text(chr(10).join(lines), encoding="utf-8")
