# Corner catalogs: contiguous fractions of a lap. Bahrain ranges calibrated
# from F1 26 telemetry; others are layout-informed approximations and refine
# automatically once you import a session (outline + optional re-fit later).
def _seg(cid: str, name: str, a: float, b: float, kind: str = "corner", apex: float | None = None) -> dict:
    d: dict = {"id": cid, "name": name, "start_frac": a, "end_frac": b, "kind": kind}
    if apex is not None:
        d["apex_frac"] = apex
    return d


